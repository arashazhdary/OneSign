// Function to apply improved translations
function applyImprovedTranslations(data, improvements) {
  for (const section in improvements) {
    if (data[section]) {
      for (const key in improvements[section]) {
        if (improvements[section][key] !== undefined) {
          data[section][key] = improvements[section][key];
        } else {
          // Remove invalid keys
          delete data[section][key];
        }
      }
    }
  }
}

